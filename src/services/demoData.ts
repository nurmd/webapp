/**
 * Returns all documents formatted for PouchDB / CouchDB _bulk_docs API
 */
export function buildCouchDbDocs(revMap: Record<string, string> = {}): any[] {
  const timestamp = new Date().toISOString();
  const docs: any[] = [];

  const addDoc = (type: string, id: string, entity: any) => {
    const docId = `${type}:${id}`;
    const doc: any = {
      ...entity,
      _id: docId,
      docType: type,
      syncedAt: timestamp,
    };
    if (revMap[docId]) {
      doc._rev = revMap[docId];
    }
    docs.push(doc);
  };

  // Company Profile
  addDoc('company', DEMO_COMPANY.id || 'COMP-001', DEMO_COMPANY);

  // Bank Accounts
  DEMO_BANK_ACCOUNTS.forEach((b) => addDoc('bank_account', b.id, b));

  // Items
  DEMO_ITEMS.forEach((i) => addDoc('item', i.id, i));

  // Parties
  DEMO_PARTIES.forEach((p) => addDoc('party', p.id, p));

  // Invoices
  DEMO_INVOICES.forEach((inv) => addDoc('invoice', inv.id, inv));

  // Purchases
  DEMO_PURCHASES.forEach((pur) => addDoc('purchase', pur.id, pur));

  // Expenses
  DEMO_EXPENSES.forEach((exp) => addDoc('expense', exp.id, exp));

  // Loans
  DEMO_LOANS.forEach((loan) => addDoc('loan', loan.id, loan));

  // Loan Transactions
  DEMO_LOAN_TRANSACTIONS.forEach((txn) => addDoc('loan_txn', txn.id, txn));

  // Cash Bank Transactions
  DEMO_CASH_BANK_TXNS.forEach((txn) => addDoc('cash_bank_txn', txn.id, txn));

  // Vouchers
  DEMO_VOUCHERS.forEach((v) => addDoc('voucher', v.id, v));

  return docs;
}
